class Solution {
    public int firstMissingPositive(int[] nums) {
        int n = nums.length;

        // Fase 1: poner cada número en su lugar
        for (int i = 0; i < n; i++) {
            while (nums[i] > 0 && nums[i] <= n && nums[nums[i] - 1] != nums[i]) {
                int target = nums[i] - 1;
                int temp = nums[target];
                nums[target] = nums[i];
                nums[i] = temp;
            }
        }

        // Fase 2: buscar la primera posición incorrecta
        for (int i = 0; i < n; i++) {
            if (nums[i] != i + 1) return i + 1;
        }
        return n + 1;
    }
}